#!/bin/sh
# Checks the dotfiles source tree: every script parses, every config loads, and
# every template renders when chezmoi is available.
#
# usage: tests/check.sh [--shellcheck]
set -u

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
use_shellcheck=false
[ "${1:-}" = "--shellcheck" ] && use_shellcheck=true

checks=0
fails=0
tmp=$(mktemp -d) || exit 1
trap 'rm -rf "$tmp"' EXIT

ok() { checks=$((checks + 1)); printf 'ok   %s\n' "$*"; }
no() { checks=$((checks + 1)); fails=$((fails + 1)); printf 'FAIL %s\n' "$*" >&2; }
skip() { printf 'skip %s\n' "$*"; }
rel() { printf '%s' "${1#"$root"/}"; }

syntax() {
    # syntax <interpreter> <path> [interpreter flags]
    if "$1" -n "$2" 2>"$tmp/err"; then
        ok "syntax $(rel "$2") ($1)"
    else
        no "syntax $(rel "$2") ($1)"
        sed 's/^/     /' "$tmp/err" >&2
    fi
}

# --- shell scripts

for script in "$root"/dot_local/bin/executable_*; do
    [ -f "$script" ] || continue
    syntax sh "$script"
done

# zsh is only installed on macOS; `sh -n` cannot parse zsh constructs.
if command -v zsh >/dev/null 2>&1; then
    syntax zsh "$root/dot_zshrc"
else
    skip "syntax dot_zshrc (zsh not installed)"
fi

if command -v fish >/dev/null 2>&1; then
    for fish_file in "$root"/dot_config/fish/config.fish "$root"/dot_config/fish/conf.d/*.fish; do
        [ -f "$fish_file" ] || continue
        if fish -n "$fish_file" 2>"$tmp/err"; then
            ok "syntax $(rel "$fish_file") (fish)"
        else
            no "syntax $(rel "$fish_file") (fish)"
            sed 's/^/     /' "$tmp/err" >&2
        fi
    done
else
    skip "syntax dot_config/fish (fish not installed)"
fi

# --- TOML

toml() {
    if python3 -c 'import tomllib' >/dev/null 2>&1; then
        if python3 -c 'import sys, tomllib; tomllib.load(open(sys.argv[1], "rb"))' "$1" 2>"$tmp/err"; then
            ok "toml $(rel "$1")"
        else
            no "toml $(rel "$1")"
            sed 's/^/     /' "$tmp/err" >&2
        fi
    else
        skip "toml $(rel "$1") (python3 tomllib missing)"
    fi
}

for cfg in "$root"/dot_config/mise/config.toml "$root"/dot_config/helix/config.toml "$root"/dot_config/helix/languages.toml; do
    [ -f "$cfg" ] && toml "$cfg"
done

# --- templates
#
# Rendered hermetically: a throwaway HOME gets a config generated by the real
# `chezmoi init` template, so the prompts, the per-OS data, and every other
# template are exercised without touching the operator's chezmoi config.
# `execute-template` cannot run the init template itself (prompt functions only
# exist during `init`), which is why the generated config is reused below.

if ! command -v chezmoi >/dev/null 2>&1; then
    skip "chezmoi templates (chezmoi not installed)"
else
    chome=$tmp/chezmoi-home
    mkdir -p "$chome/.config"
    if HOME=$chome XDG_CONFIG_HOME=$chome/.config chezmoi init \
            --source "$root" --destination "$tmp/chezmoi-dest" --no-tty \
            --promptString "Your full name=Test User" \
            --promptString "Your email=test@example.com" \
            --promptString "Machine profile (personal or work)=personal" \
            --promptBool "Is this a laptop=true" \
            --promptBool "Is this a headless machine (no GUI apps)=false" \
            >"$tmp/init.log" 2>&1; then
        ok "chezmoi init renders .chezmoi.toml.tmpl"
        generated=$chome/.config/chezmoi/chezmoi.toml
        if python3 -c 'import tomllib' >/dev/null 2>&1; then
            if python3 -c 'import sys, tomllib; tomllib.load(open(sys.argv[1], "rb"))' "$generated" 2>"$tmp/err"; then
                ok "toml generated chezmoi.toml"
            else
                no "toml generated chezmoi.toml"
                sed 's/^/     /' "$tmp/err" >&2
            fi
        else
            skip "toml generated chezmoi.toml (python3 tomllib missing)"
        fi
        for tmpl in dot_gitconfig.tmpl dot_config/git/personal.inc.tmpl \
                    dot_config/git/work.inc.tmpl run_once_install.sh.tmpl; do
            if HOME=$chome XDG_CONFIG_HOME=$chome/.config chezmoi --source "$root" \
                    execute-template < "$root/$tmpl" > "$tmp/render" 2>"$tmp/err"; then
                ok "template $tmpl"
                case $tmpl in
                    *.sh.tmpl)
                        if sh -n "$tmp/render" 2>"$tmp/err"; then
                            ok "syntax rendered $tmpl"
                        else
                            no "syntax rendered $tmpl"
                            sed 's/^/     /' "$tmp/err" >&2
                        fi ;;
                esac
            else
                no "template $tmpl"
                sed 's/^/     /' "$tmp/err" >&2
            fi
        done
    else
        no "chezmoi init (the init template did not render)"
        sed 's/^/     /' "$tmp/init.log" >&2
    fi
fi

# --- content lints

if grep -rnE 'curl|wget' "$root/dot_config/fish" >/dev/null 2>&1; then
    no "fish startup downloads at shell start"
    grep -rnE 'curl|wget' "$root/dot_config/fish" | sed 's/^/     /' >&2
else
    ok "no downloader in fish startup"
fi

nix_pattern='(^|[^a-z])nix([^a-z]|$)|nixos|nixpkgs|nix-shell|doas|pacman'
if grep -rniE "$nix_pattern" "$root/dot_config" "$root/dot_local" \
        "$root/dot_zshrc" "$root/dot_gitconfig.tmpl" >/dev/null 2>&1; then
    no "Nix or Arch assumptions in managed files"
    grep -rniE "$nix_pattern" "$root/dot_config" "$root/dot_local" \
        "$root/dot_zshrc" "$root/dot_gitconfig.tmpl" | sed 's/^/     /' >&2
else
    ok "no Nix or Arch assumptions in managed files"
fi

secret_pattern='BEGIN [A-Z ]*PRIVATE KEY|ghp_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}'
if grep -rInE "$secret_pattern" "$root/dot_config" "$root/dot_local" \
        "$root/dot_zshrc" "$root/dot_gitconfig.tmpl" \
        "$root/run_once_install.sh.tmpl" >/dev/null 2>&1; then
    no "secret material in a managed file"
else
    ok "no secret material in managed files"
fi

if grep -qx 'README.md' "$root/.chezmoiignore" && grep -qx 'tests' "$root/.chezmoiignore"; then
    ok ".chezmoiignore hides README.md and tests"
else
    no ".chezmoiignore must hide README.md and tests"
fi

# --- optional shellcheck

if $use_shellcheck; then
    if command -v shellcheck >/dev/null 2>&1; then
        for script in "$root"/dot_local/bin/executable_*; do
            [ -f "$script" ] || continue
            # SC3043: `local` is not POSIX, but every real /bin/sh implements it.
            if shellcheck -s sh -e SC3043 "$script" >"$tmp/out" 2>&1; then
                ok "shellcheck $(rel "$script")"
            else
                no "shellcheck $(rel "$script")"
                sed 's/^/     /' "$tmp/out" >&2
            fi
        done
    else
        skip "shellcheck (not installed)"
    fi
fi

printf '\n%d checks, %d failed\n' "$checks" "$fails"
[ "$fails" -eq 0 ]

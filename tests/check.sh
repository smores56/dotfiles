#!/bin/sh
# Checks the dotfiles source tree: every script parses, every config loads, and
# every template renders when chezmoi is available.
#
# usage: tests/check.sh [--shellcheck]
set -u

root=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
use_shellcheck=false
[ "${1:-}" = "--shellcheck" ] && use_shellcheck=true

checks=0
fails=0
tmp=$(mktemp -d) || exit 1
trap 'rm -rf "$tmp"' EXIT

ok() { checks=$((checks + 1)); printf 'ok   %s\n' "$*"; }
no() { checks=$((checks + 1)); fails=$((fails + 1)); printf 'FAIL %s\n' "$*" >&2; }
skip() { printf 'skip %s\n' "$*"; }
rel() { printf '%s' "${1#"$root"/}"; }

syntax() {
    # syntax <interpreter> <path> [interpreter flags]
    if "$1" -n "$2" 2>"$tmp/err"; then
        ok "syntax $(rel "$2") ($1)"
    else
        no "syntax $(rel "$2") ($1)"
        sed 's/^/     /' "$tmp/err" >&2
    fi
}

# --- shell scripts

for script in "$root"/dot_local/bin/executable_*; do
    [ -f "$script" ] || continue
    syntax sh "$script"
done

# The repository's own canonical entrypoint is not managed, but must parse.
[ -f "$root/dev" ] && syntax sh "$root/dev"

if command -v bash >/dev/null 2>&1; then
    syntax bash "$root/tests/cli.sh"
else
    skip "syntax tests/cli.sh (bash not installed)"
fi

# zsh is only installed on macOS; `sh -n` cannot parse zsh constructs.
if command -v zsh >/dev/null 2>&1; then
    syntax zsh "$root/dot_zshrc"
else
    skip "syntax dot_zshrc (zsh not installed)"
fi

if command -v fish >/dev/null 2>&1; then
    for fish_file in "$root"/dot_config/fish/config.fish "$root"/dot_config/fish/conf.d/*.fish; do
        [ -f "$fish_file" ] || continue
        if fish -n "$fish_file" 2>"$tmp/err"; then
            ok "syntax $(rel "$fish_file") (fish)"
        else
            no "syntax $(rel "$fish_file") (fish)"
            sed 's/^/     /' "$tmp/err" >&2
        fi
    done
else
    skip "syntax dot_config/fish (fish not installed)"
fi

# --- TOML

toml() {
    if python3 -c 'import tomllib' >/dev/null 2>&1; then
        if python3 -c 'import sys, tomllib; tomllib.load(open(sys.argv[1], "rb"))' "$1" 2>"$tmp/err"; then
            ok "toml $(rel "$1")"
        else
            no "toml $(rel "$1")"
            sed 's/^/     /' "$tmp/err" >&2
        fi
    else
        skip "toml $(rel "$1") (python3 tomllib missing)"
    fi
}

for cfg in "$root"/dot_config/mise/config.toml "$root"/dot_config/helix/config.toml "$root"/dot_config/helix/languages.toml "$root"/dot_aerospace.toml; do
    [ -f "$cfg" ] && toml "$cfg"
done

# AeroSpace's root keys must not fall under [exec.env-vars]; toml.load alone
# would accept the misplaced table.
if python3 -c 'import tomllib' >/dev/null 2>&1; then
    if python3 - "$root/dot_aerospace.toml" <<'PY'
import sys, tomllib
with open(sys.argv[1], "rb") as handle:
    config = tomllib.load(handle)
assert "default-root-container-layout" in config
assert "after-startup-command" in config
assert "default-root-container-layout" not in config.get("exec", {}).get("env-vars", {})
PY
    then
        ok "aerospace root settings are top-level"
    else
        no "aerospace root settings are top-level"
    fi
else
    skip "aerospace root settings (python3 tomllib missing)"
fi

# --- templates
#
# Rendered hermetically: a throwaway HOME gets a config generated by the real
# `chezmoi init` template, so the prompts, the per-OS data, and every other
# template are exercised without touching the operator's chezmoi config.
# `execute-template` cannot run the init template itself (prompt functions only
# exist during `init`), which is why the generated config is reused below.

if ! command -v chezmoi >/dev/null 2>&1; then
    skip "chezmoi templates (chezmoi not installed)"
else
    chome=$tmp/chezmoi-home
    mkdir -p "$chome/.config"
    if HOME=$chome XDG_CONFIG_HOME=$chome/.config chezmoi init \
            --source "$root" --destination "$tmp/chezmoi-dest" --no-tty \
            --promptString "Your full name=Test User" \
            --promptString "Your email=test@example.com" \
            --promptString "Machine profile (personal or work)=personal" \
            --promptBool "Is this a laptop=true" \
            --promptBool "Is this a headless machine (no GUI apps)=false" \
            >"$tmp/init.log" 2>&1; then
        ok "chezmoi init renders .chezmoi.toml.tmpl"
        generated=$chome/.config/chezmoi/chezmoi.toml
        if python3 -c 'import tomllib' >/dev/null 2>&1; then
            if python3 -c 'import sys, tomllib; tomllib.load(open(sys.argv[1], "rb"))' "$generated" 2>"$tmp/err"; then
                ok "toml generated chezmoi.toml"
            else
                no "toml generated chezmoi.toml"
                sed 's/^/     /' "$tmp/err" >&2
            fi
        else
            skip "toml generated chezmoi.toml (python3 tomllib missing)"
        fi
        for tmpl in dot_gitconfig.tmpl dot_config/git/personal.inc.tmpl \
                    dot_config/git/work.inc.tmpl dot_cargo/config.toml.tmpl \
                    dot_config/ntfy/client.yml.tmpl \
                    run_after_allowed_signers.sh.tmpl \
                    run_onchange_after_macos_defaults.sh.tmpl \
                    run_onchange_after_ntfy.sh.tmpl \
                    run_onchange_after_wallpapers.sh.tmpl \
                    run_once_before_00-install-sops.sh.tmpl \
                    run_once_before_10-sops-verify.sh.tmpl \
                    dot_Library/LaunchAgents/dev.sammohr.ntfy-subscribe.plist.tmpl \
                    dot_Library/LaunchAgents/dev.sammohr.wallpapers.plist.tmpl; do
            if HOME=$chome XDG_CONFIG_HOME=$chome/.config chezmoi --source "$root" \
                    execute-template < "$root/$tmpl" > "$tmp/render" 2>"$tmp/err"; then
                ok "template $tmpl"
                case $tmpl in
                    *.sh.tmpl)
                        if sh -n "$tmp/render" 2>"$tmp/err"; then
                            ok "syntax rendered $tmpl"
                        else
                            no "syntax rendered $tmpl"
                            sed 's/^/     /' "$tmp/err" >&2
                        fi
                        ;;
                    *.plist.tmpl)
                        if python3 -c 'import plistlib' >/dev/null 2>&1; then
                            if python3 -c 'import plistlib, sys; plistlib.load(open(sys.argv[1], "rb"))' "$tmp/render" 2>"$tmp/err"; then
                                ok "plist rendered $tmpl"
                            else
                                no "plist rendered $tmpl"
                                sed 's/^/     /' "$tmp/err" >&2
                            fi
                        else
                            skip "plist rendered $tmpl (python3 plistlib missing)"
                        fi
                        ;;
                esac
            else
                no "template $tmpl"
                sed 's/^/     /' "$tmp/err" >&2
            fi
                done

        # A work-profile init must render the owner-keyed work settings, not
        # just the personal defaults.
        work_home=$tmp/work-home
        mkdir -p "$work_home/.config"
        if HOME=$work_home XDG_CONFIG_HOME=$work_home/.config chezmoi init \
                --source "$root" --destination "$tmp/work-dest" --no-tty \
                --promptString "Your full name=Test User" \
                --promptString "Your email=test@example.com" \
                --promptString "Machine profile (personal or work)=work" \
                --promptString "Work email=work@example.com" \
                --promptString "Work GitHub owners (space-separated)=blitzy-ai blitzy-platform" \
                --promptBool "Is this a laptop=true" \
                --promptBool "Is this a headless machine (no GUI apps)=false" \
                >"$tmp/work-init.log" 2>&1; then
            work_cfg=$work_home/.config/chezmoi/chezmoi.toml
            if HOME=$work_home XDG_CONFIG_HOME=$work_home/.config chezmoi \
                    --config "$work_cfg" --source "$root" execute-template \
                    < "$root/dot_gitconfig.tmpl" > "$tmp/work-gitconfig" 2>"$tmp/err" \
                && grep -q 'repos_root = "~/ghq"' "$work_cfg" \
                && grep -q 'gitdir:~/ghq/github.com/blitzy-ai/' "$tmp/work-gitconfig" \
                && grep -q 'gitdir:~/Blitzy/' "$tmp/work-gitconfig"; then
                ok "work profile renders owner and flat-root includes"
            else
                no "work profile renders owner and flat-root includes"
                sed 's/^/     /' "$tmp/err" >&2
            fi
            if HOME=$work_home XDG_CONFIG_HOME=$work_home/.config chezmoi \
                    --config "$work_cfg" --source "$root" execute-template \
                    < "$root/dot_config/git/work.inc.tmpl" > "$tmp/work-inc" 2>"$tmp/err" \
                && grep -q 'flow = "pr"' "$tmp/work-inc" \
                && grep -q 'branchTemplate = "{ticket}-{slug}"' "$tmp/work-inc" \
                && grep -q 'branchTemplateUnticketed = "{type}/{slug}"' "$tmp/work-inc"; then
                ok "work include renders flow and ticket branch templates"
            else
                no "work include renders flow and ticket branch templates"
                sed 's/^/     /' "$tmp/err" >&2
            fi
        else
            no "chezmoi work-profile init"
            sed 's/^/     /' "$tmp/work-init.log" >&2
        fi

        # The installer carries a branch per OS. Render both, so a syntax error
        # in the branch the current machine cannot run is still caught here.
        for os_name in linux darwin; do
            cfg=$tmp/chezmoi-$os_name.toml
            sed "s/^    os = \"[a-z]*\"/    os = \"$os_name\"/" "$generated" > "$cfg"
            if HOME=$chome XDG_CONFIG_HOME=$chome/.config chezmoi --config "$cfg" \
                    --source "$root" execute-template \
                    < "$root/run_once_install.sh.tmpl" > "$tmp/install-$os_name.sh" 2>"$tmp/err"; then
                ok "template run_once_install.sh.tmpl ($os_name)"
                if sh -n "$tmp/install-$os_name.sh" 2>"$tmp/err"; then
                    ok "syntax rendered run_once_install.sh.tmpl ($os_name)"
                else
                    no "syntax rendered run_once_install.sh.tmpl ($os_name)"
                    sed 's/^/     /' "$tmp/err" >&2
                fi
            else
                no "template run_once_install.sh.tmpl ($os_name)"
                sed 's/^/     /' "$tmp/err" >&2
            fi
        done
        if grep -q 'rpm-ostree' "$tmp/install-linux.sh" \
                && ! grep -q 'brew install' "$tmp/install-linux.sh" \
                && ! grep -q 'rpm-ostree' "$tmp/install-darwin.sh"; then
            ok "the installer renders one branch per OS"
        else
            no "the installer renders one branch per OS"
        fi

        # A config written before the `os` key existed must still render: the
        # template falls back to .chezmoi.os.
        grep -v '^    os = ' "$generated" > "$tmp/chezmoi-legacy.toml"
        if HOME=$chome XDG_CONFIG_HOME=$chome/.config chezmoi \
                --config "$tmp/chezmoi-legacy.toml" --source "$root" execute-template \
                < "$root/run_once_install.sh.tmpl" > "$tmp/install-legacy.sh" 2>"$tmp/err" \
                && sh -n "$tmp/install-legacy.sh" 2>"$tmp/err"; then
            ok "run_once_install.sh.tmpl renders without an os key"
        else
            no "run_once_install.sh.tmpl renders without an os key"
            sed 's/^/     /' "$tmp/err" >&2
        fi
    else
        no "chezmoi init (the init template did not render)"
        sed 's/^/     /' "$tmp/init.log" >&2
    fi
fi

# --- content lints

if grep -rnE 'curl|wget' "$root/dot_config/fish" >/dev/null 2>&1; then
    no "fish startup downloads at shell start"
    grep -rnE 'curl|wget' "$root/dot_config/fish" | sed 's/^/     /' >&2
else
    ok "no downloader in fish startup"
fi

nix_pattern='(^|[^a-z])nix([^a-z]|$)|nixos|nixpkgs|nix-shell|doas|pacman'
if grep -rniE "$nix_pattern" "$root/dot_config" "$root/dot_local" \
        "$root/dot_zshrc" "$root/dot_gitconfig.tmpl" >/dev/null 2>&1; then
    no "Nix or Arch assumptions in managed files"
    grep -rniE "$nix_pattern" "$root/dot_config" "$root/dot_local" \
        "$root/dot_zshrc" "$root/dot_gitconfig.tmpl" | sed 's/^/     /' >&2
else
    ok "no Nix or Arch assumptions in managed files"
fi

secret_pattern='BEGIN [A-Z ]*PRIVATE KEY|ghp_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}'
if grep -rInE "$secret_pattern" "$root/dot_config" "$root/dot_local" \
        "$root/dot_zshrc" "$root/dot_gitconfig.tmpl" \
        "$root/run_once_install.sh.tmpl" >/dev/null 2>&1; then
    no "secret material in a managed file"
else
    ok "no secret material in managed files"
fi

if grep -qx 'README.md' "$root/.chezmoiignore" && grep -qx 'tests' "$root/.chezmoiignore" \
        && grep -qx '.github' "$root/.chezmoiignore" \
        && grep -qx 'Containerfile' "$root/.chezmoiignore" \
        && grep -qx 'dev' "$root/.chezmoiignore" \
        && grep -qx '.containerignore' "$root/.chezmoiignore" \
        && grep -qx '.gitignore' "$root/.chezmoiignore"; then
    ok ".chezmoiignore hides every repository-only file"
else
    no ".chezmoiignore must hide README.md, tests, .github, Containerfile, dev, and the ignore files"
fi

# --- behavioral tests
#
# The wrappers are the parts that can destroy work, so they are exercised
# against throwaway repositories rather than only parsed.
if command -v git >/dev/null 2>&1 && command -v bash >/dev/null 2>&1; then
    if bash "$root/tests/cli.sh"; then
        ok "behavioral tests (tests/cli.sh)"
    else
        no "behavioral tests (tests/cli.sh)"
    fi
else
    skip "behavioral tests (git or bash not installed)"
fi

# --- optional shellcheck

if $use_shellcheck; then
    if command -v shellcheck >/dev/null 2>&1; then
        for script in "$root"/dot_local/bin/executable_*; do
            [ -f "$script" ] || continue
            # SC3043: `local` is not POSIX, but every real /bin/sh implements it.
            if shellcheck -s sh -e SC3043 "$script" >"$tmp/out" 2>&1; then
                ok "shellcheck $(rel "$script")"
            else
                no "shellcheck $(rel "$script")"
                sed 's/^/     /' "$tmp/out" >&2
            fi
        done
        if shellcheck -s bash "$root/tests/cli.sh" >"$tmp/out" 2>&1; then
            ok "shellcheck tests/cli.sh"
        else
            no "shellcheck tests/cli.sh"
            sed 's/^/     /' "$tmp/out" >&2
        fi
    else
        skip "shellcheck (not installed)"
    fi
fi

printf '\n%d checks, %d failed\n' "$checks" "$fails"
[ "$fails" -eq 0 ]

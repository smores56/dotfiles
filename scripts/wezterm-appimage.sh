#!/bin/sh
# Install the pinned WezTerm AppImage under ~/.local/opt/wezterm and point
# ~/.local/bin/wezterm at it.
#
# The Flathub build is the only other packaged option and it is abandoned on
# org.freedesktop.Platform 23.08, whose Mesa predates this laptop's GPU
# (Panther Lake, 0xb082) and refuses to initialize EGL there. The AppImage
# bundles WezTerm but links against the host GL stack, so it renders.
#
# The stable release is pinned because the nightly tag is rewritten daily and
# cannot be checksum-pinned. Bump VERSION and SHA256 together.
set -eu

VERSION=20240203-110809-5046fc22
ASSET="WezTerm-${VERSION}-Ubuntu20.04.AppImage"
SHA256=34010a07076d2272c4d4f94b5e0dae608a679599e8d729446323f88f956c60f0
URL="https://github.com/wezterm/wezterm/releases/download/${VERSION}/${ASSET}"

[ "$(uname -s)" = Linux ] || exit 0

prefix=$HOME/.local/opt/wezterm
dest=$prefix/$VERSION
wrapper=$HOME/.local/bin/wezterm

log() { printf 'wezterm-appimage: %s\n' "$*"; }

if [ -x "$dest/AppRun" ] && [ -x "$wrapper" ]; then
    log "$VERSION already installed"
    exit 0
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

log "fetching $ASSET"
curl -fsSLo "$tmp/$ASSET" "$URL"
printf '%s  %s\n' "$SHA256" "$tmp/$ASSET" | sha256sum -c - >/dev/null
chmod 755 "$tmp/$ASSET"

(cd "$tmp" && ./"$ASSET" --appimage-extract >/dev/null)

mkdir -p "$prefix"
rm -rf "$dest"
mv "$tmp/squashfs-root" "$dest"
mkdir -p "$HOME/.local/bin"
cat >"$wrapper" <<EOF
#!/bin/sh
# Generated by dotfiles scripts/wezterm-appimage.sh; do not edit.
exec "$dest/AppRun" "\$@"
EOF
chmod 755 "$wrapper"
log "installed $VERSION -> $wrapper"

for old in "$prefix"/*; do
    [ -d "$old" ] || continue
    [ "$old" = "$dest" ] && continue
    rm -rf "$old"
    log "removed $old"
done

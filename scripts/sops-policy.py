#!/usr/bin/env python3
"""One SOPS policy for every repository.

The recipients below are the canonical set. `render` writes a repository's
committed config from them; `check` is keyless and fails when a ciphertext, a
rule, or the config disagrees; `rekey` is the only mode that needs an identity.

The machine identity is deliberately in every rule: one unattended reader
boots the host and applies the tenant. Narrowing it is a future design, not a
comment in a file that the rules contradict.

usage:
  scripts/sops-policy.py render --profile platform [--out PATH]
  scripts/sops-policy.py check --repo .
  scripts/sops-policy.py rekey --repo . [--rotate]
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ADMIN = "age1skuwunreduvw8gtkzyf9atsyjnku388ly8c252h3qger84fg5d7q4kf6xs"
MACHINE = "age1dy66kuzcvu7tgl64pxrjymdt3ndk7g2ftsqc0nx4s8fhyv8zfyyq2h0756"
YK1 = "age18suc3usnfah6g3fldvhhvmchyupg3tp2p5vgzfuprvcn6untva9qem4lf0"
YK2 = "age1zepedng5vqafu95hysrxl0kadreshg2yc07epfqky5fuq2nmy5fqg649lf"
YK3 = "age1xqpw0qy2mk98ptvvh5y0sxtlrxs036nng2868zd6dc4wdcrrm5mqd6pnpf"
RECIPIENTS = [ADMIN, MACHINE, YK1, YK2, YK3]
ANCHORS = ["admin", "machine", "yk1", "yk2", "yk3"]
DIGEST = hashlib.sha256(("\n".join(RECIPIENTS) + "\n").encode()).hexdigest()[:16]

PROFILES = {
    "platform": {
        "rule": r"^secrets/.*\.yaml$",
        "config": ".sops.yaml",
        "must": r"^secrets/.*\.yaml$",
    },
    "apps": {
        "rule": r"secrets\.sops\.json$",
        "config": ".sops.yaml",
        "must": r"secrets\.sops\.json$",
    },
    # The canonical config is read from outside the repository too, so its rule
    # is a catch-all; `must` is the only path that has to be encrypted here.
    "dotfiles": {
        "rule": r".*",
        "config": "home/.config/sops/sops.yaml",
        "must": r"^sops\.yaml$",
    },
}


def err(message: str) -> None:
    print(f"sops-policy: {message}", file=sys.stderr)


def run(args: list[str]) -> str:
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or f"{' '.join(args)} failed")
    return result.stdout


def render(profile: str) -> str:
    rule = PROFILES[profile]["rule"]
    lines = [
        f"# Generated by scripts/sops-policy.py {DIGEST}. Do not edit by hand.",
        "# Run `scripts/sops-policy.py render --profile " + profile + "`.",
        "#",
        "# Every reader below can decrypt every file the rule matches. The admin",
        "# identity is first so a no-token decrypt prompts once; the machine",
        "# identity is the unattended host reader and is intentional.",
        "keys:",
    ]
    for anchor, recipient in zip(ANCHORS, RECIPIENTS):
        lines.append(f"  - &{anchor} {recipient}")
    lines += ["creation_rules:", f"  - path_regex: {rule}", "    key_groups:", "      - age:"]
    for anchor in ANCHORS:
        lines.append(f"          - *{anchor}")
    return "\n".join(lines) + "\n"


def age_recipients(path: Path) -> list[str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    found = re.findall(r'"recipient"\s*:\s*"(age1[^"]+)"', text)
    if found:
        return found
    return re.findall(r"^\s*-?\s*recipient:\s*(age1\S+)\s*$", text, re.MULTILINE)


def config_parts(path: Path) -> tuple[list[str], list[str]]:
    text = path.read_text(encoding="utf-8")
    before, _, _ = text.partition("creation_rules:")
    keys = re.findall(r"age1[a-z0-9]+", before)
    rules = []
    for match in re.finditer(r"^\s*-?\s*path_regex:\s*(.+?)\s*$", text, re.MULTILINE):
        rule = match.group(1).strip()
        if len(rule) >= 2 and rule[0] == rule[-1] and rule[0] in "\"'":
            rule = rule[1:-1]
        rules.append(rule)
    return keys, rules


def tracked(repo: Path) -> list[str]:
    return run(["git", "-C", str(repo), "ls-files"]).splitlines()


def check(repo: Path, config: Path | None) -> int:
    if config is None:
        found = [
            (profile, repo / spec["config"])
            for profile, spec in PROFILES.items()
            if (repo / spec["config"]).exists()
        ]
        if not found:
            err(f"no SOPS config under {repo}")
            return 1
        config = found[0][1]

    if not config.exists():
        err(f"{config} is missing")
        return 1

    text = config.read_text(encoding="utf-8")
    if f"sops-policy.py {DIGEST}" not in text:
        err(f"{config} is not rendered from canonical policy {DIGEST}")
        return 1

    keys, rules = config_parts(config)
    if keys != RECIPIENTS:
        err(f"{config} recipients are {keys}, want {RECIPIENTS}")
        return 1
    if not rules:
        err(f"{config} has no creation rule")
        return 1
    # The rule, not the config path, identifies the profile: platform and apps
    # both commit a .sops.yaml, so the path alone is ambiguous.
    profile = next(
        (name for name, spec in PROFILES.items() if spec["rule"] in rules),
        None,
    )
    if profile is None:
        err(f"{config} matches no known policy profile")
        return 1

    problems = 0
    files = tracked(repo)
    encrypted: dict[str, list[str]] = {}
    for rel in files:
        recipients = age_recipients(repo / rel)
        if recipients:
            encrypted[rel] = recipients

    for rel, recipients in encrypted.items():
        if not any(re.search(rule, rel) for rule in rules):
            err(f"{rel} is encrypted but matched by no creation rule")
            problems += 1
            continue
        if recipients != RECIPIENTS:
            err(f"{rel} recipients are {recipients}, want {RECIPIENTS}")
            problems += 1

    must = PROFILES[profile]["must"] if profile else None
    for rel in files:
        if rel in encrypted:
            continue
        if must and re.search(must, rel):
            err(f"{rel} must be encrypted but has no SOPS metadata")
            problems += 1

    if problems:
        return 1
    print(
        f"ok   {profile or 'repo'}: {len(encrypted)} ciphertext file(s), "
        f"{len(rules)} rule(s), canonical {DIGEST}"
    )
    return 0


def rekey(repo: Path, config: Path, rotate: bool) -> int:
    count = 0
    for rel in tracked(repo):
        path = repo / rel
        if not age_recipients(path):
            continue
        args = ["sops", "--config", str(config), "updatekeys", "-y", str(path)]
        run(args)
        if rotate:
            run(["sops", "--config", str(config), "rotate", "--in-place", str(path)])
        count += 1
    print(f"ok   rekeyed {count} ciphertext file(s)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    p_render = sub.add_parser("render")
    p_render.add_argument("--profile", choices=sorted(PROFILES), required=True)
    p_render.add_argument("--out")

    p_check = sub.add_parser("check")
    p_check.add_argument("--repo", default=".")
    p_check.add_argument("--config")

    p_rekey = sub.add_parser("rekey")
    p_rekey.add_argument("--repo", default=".")
    p_rekey.add_argument("--config")
    p_rekey.add_argument("--rotate", action="store_true")

    args = parser.parse_args()

    if args.command == "render":
        content = render(args.profile)
        if args.out:
            Path(args.out).write_text(content, encoding="utf-8")
        else:
            sys.stdout.write(content)
        return 0

    repo = Path(args.repo).resolve()
    if not (repo / ".git").exists():
        err(f"{repo} is not a git checkout")
        return 2

    if args.command == "check":
        return check(repo, Path(args.config).resolve() if args.config else None)

    config = Path(args.config).resolve() if args.config else repo / ".sops.yaml"
    try:
        return rekey(repo, config, args.rotate)
    except RuntimeError as exc:
        err(str(exc))
        return 1


if __name__ == "__main__":
    sys.exit(main())
